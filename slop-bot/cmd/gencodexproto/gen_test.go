const miniSchema = "testdata/schema"

// generateMini renders testdata/schema, a miniature bundle with one case per
// mapping rule, and returns the source with gofmt's alignment collapsed so
// lines can be matched as written.
func generateMini(t *testing.T, roots ...string) string {
	t.Helper()
	defs, err := loadBundle(miniSchema)
	require.NoError(t, err)
	src, err := newGenerator("protocol", "// Code generated by test; DO NOT EDIT.\n", defs).
		generate(roots, []methodGroup{{def: "ClientRequest"}, {def: "ServerRequest", all: true}})
	require.NoError(t, err)
	typeCheck(t, src)
	return regexp.MustCompile(`[ \t]+`).ReplaceAllString(string(src), " ")
}

func typeCheck(t *testing.T, src []byte) {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "protocol_gen.go", src, parser.ParseComments)
	require.NoError(t, err)
	_, err = (&types.Config{Importer: importer.Default()}).Check("protocol", fset, []*ast.File{f}, nil)
	require.NoError(t, err, "the generated source must compile")
}

func TestGeneratedFields(t *testing.T) {
	t.Parallel()
	src := generateMini(t, "TurnStartParams", "InitializeParams")
	for _, want := range []string{
		"// Code generated by test; DO NOT EDIT.",
		// The first line of a description only.
		"// Starts a turn.\ntype TurnStartParams struct {",
		// Required: no omitempty; initialisms in capitals.
		"ThreadID string `json:\"threadId\"`",
		"Input []UserInput `json:\"input\"`",
		// A required struct is a value, an optional or nullable one a pointer.
		"Origin TurnError `json:\"origin\"`",
		"Error *TurnError `json:\"error,omitempty\"`",
		"Window *TurnStartParamsWindow `json:\"window,omitempty\"`",
		// A nullable scalar is the scalar, omitted when empty.
		"Effort ReasoningEffort `json:\"effort,omitempty\"`",
		"Config map[string]any `json:\"config,omitempty\"`",
		"Counts map[string]int64 `json:\"counts\"`",
		"Anything json.RawMessage `json:\"anything,omitempty\"`",
		"ReceiverThreadIDs []string",
		"type ReasoningEffort string",
		"ClientInfo ClientInfo `json:\"clientInfo\"`",
	} {
		assert.Contains(t, src, want)
	}
	assert.NotContains(t, src, "type Unused", "only what the roots reach is generated")
}

func TestGeneratedEnumsAndMixedUnions(t *testing.T) {
	t.Parallel()
	src := generateMini(t, "TurnStartParams")
	assert.Contains(t, src, "type SandboxMode string")
	assert.Contains(t, src, "SandboxModeDangerFullAccess SandboxMode = \"danger-full-access\"")
	// A union of strings and objects is any, with its strings as constants.
	assert.Contains(t, src, "type AskForApproval = any")
	assert.Contains(t, src, "AskForApprovalOnRequest = \"on-request\"")
	assert.Contains(t, src, "AskForApprovalNever = \"never\"")
}

func TestGeneratedUnionWithoutAnObjectIsRawJSON(t *testing.T) {
	t.Parallel()
	src := generateMini(t, "TurnStartParams")
	// A string-or-array union flattened into a struct would decode neither;
	// raw JSON, as an alias so RawMessage keeps its (Un)MarshalJSON.
	assert.Contains(t, src, "type OutputBody = json.RawMessage")
	assert.NotContains(t, src, "type OutputBody struct")
}

func TestGeneratedObjectUnionIsFlattened(t *testing.T) {
	t.Parallel()
	src := generateMini(t, "TurnStartParams")
	// Every variant's fields, nested alternatives included; required only
	// where every variant requires it.
	assert.Contains(t, src, "Type string `json:\"type\"`")
	assert.Contains(t, src, "Text string `json:\"text,omitempty\"`")
	assert.Contains(t, src, "URL string `json:\"url,omitempty\"`")
	assert.Contains(t, src, "FileID string `json:\"fileId,omitempty\"`")
	// status is an enum, a string and an integer across the variants: no
	// one Go type fits, so it stays raw.
	assert.Contains(t, src, "Status json.RawMessage `json:\"status,omitempty\"`")
	// phase is two different enums and a named string: some string, so a
	// string, not the first variant's enum.
	assert.Contains(t, src, "Phase string `json:\"phase,omitempty\"`")
	// mode is two different enums alone: the bug was typing it as the first.
	assert.Contains(t, src, "Mode string `json:\"mode,omitempty\"`")
	// The discriminator's values, once each, though image is two chains.
	assert.Contains(t, src, "UserInputTypeText = \"text\"")
	assert.Equal(t, 1, strings.Count(src, "UserInputTypeImage ="))
}

func TestGeneratedMethods(t *testing.T) {
	t.Parallel()
	src := generateMini(t, "TurnStartParams")
	assert.Contains(t, src, "// MethodTurnStart takes TurnStartParams.\n MethodTurnStart = \"turn/start\"")
	assert.NotContains(t, src, "MethodInitialize ", "its params weren't generated")
	assert.NotContains(t, src, "not/generated")
	assert.Contains(t, src, "MethodItemCommandExecutionRequestApproval = \"item/commandExecution/requestApproval\"",
		"every server request is named, generated or not")
}

func TestUnknownRootFails(t *testing.T) {
	t.Parallel()
	defs, err := loadBundle(miniSchema)
	require.NoError(t, err)
	_, err = newGenerator("protocol", "", defs).generate([]string{"NoSuchThing"}, nil)
	assert.ErrorContains(t, err, "NoSuchThing")
}

func TestRunWritesTheFileFromASchemaDirectory(t *testing.T) {
	t.Parallel()
	out := filepath.Join(t.TempDir(), "protocol_gen.go")
	require.NoError(t, run(&options{out: out, schema: miniSchema, pkg: "protocol", version: "codex-cli 0.0.0", roots: []string{"TurnStartParams"}}))
	src, err := os.ReadFile(out)
	require.NoError(t, err)
	assert.True(t, strings.HasPrefix(string(src), "// Code generated by slop-bot/cmd/gencodexproto"))
	assert.Contains(t, string(src), "// Schema of codex-cli 0.0.0.")
	assert.Contains(t, string(src), "type TurnStartParams struct")
	attrs, err := os.ReadFile(filepath.Join(filepath.Dir(out), ".gitattributes"))
	require.NoError(t, err, "the generator keeps its output marked as generated")
	assert.Contains(t, string(attrs), "protocol_gen.go linguist-generated=true")
}

func TestRunWritesNothingWhenARootIsMissing(t *testing.T) {
	t.Parallel()
	out := filepath.Join(t.TempDir(), "protocol_gen.go")
	// The miniature lacks the harness's own roots.
	err := run(&options{out: out, schema: miniSchema, pkg: "protocol"})
	assert.ErrorContains(t, err, "is not in the schema")
	_, statErr := os.Stat(out)
	assert.True(t, os.IsNotExist(statErr))
}

