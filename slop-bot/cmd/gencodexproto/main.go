// Command gencodexproto generates the Go types of Codex's app-server
// protocol that the codex/app-server harness speaks, from the JSON Schema
// `codex app-server generate-json-schema --experimental` writes. Run it with
// `go generate ./internal/harness/codex/protocol` and commit the result;
// regenerate on a Codex version bump, then re-record the codec fixtures.
//
// Only the messages the harness uses (roots) and what they reference are
// generated: the whole protocol is over 700 definitions.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// roots are the messages the harness sends or reads. Add one here, and
// regenerate, to use another.
var roots = []string{
	// client → server
	"InitializeParams", "InitializeResponse",
	"ThreadStartParams", "ThreadStartResponse",
	"ThreadResumeParams", "ThreadResumeResponse",
	"TurnStartParams", "TurnStartResponse",
	"TurnSteerParams", "TurnSteerResponse",
	"TurnInterruptParams",
	"ThreadBackgroundTerminalsCleanParams",
	// server → client notifications
	"TurnStartedNotification", "TurnCompletedNotification",
	"ItemStartedNotification", "ItemCompletedNotification",
	"ThreadTokenUsageUpdatedNotification",
	"AccountRateLimitsUpdatedNotification",
	"ErrorNotification",
	// server → client requests: what the harness answers them with
	"PermissionsRequestApprovalParams",
	// the command the merge guard classifies
	"CommandExecutionRequestApprovalParams",
	"CommandExecutionRequestApprovalResponse",
	"FileChangeRequestApprovalResponse",
	"PermissionsRequestApprovalResponse",
	"ApplyPatchApprovalResponse",
	"ExecCommandApprovalResponse",
	"McpServerElicitationRequestResponse",
	"ToolRequestUserInputResponse",
}

var methodGroups = []methodGroup{
	{def: "ClientRequest"},
	{def: "ServerNotification"},
	// Every server request is named, so the harness can answer each one,
	// even those whose params it never reads.
	{def: "ServerRequest", all: true},
	{def: "ClientNotification", all: true},
}

func main() {
	out := flag.String("out", "protocol_gen.go", "file to write")
	schema := flag.String("schema", "", "read a schema directory written earlier, instead of running codex")
	codex := flag.String("codex", "codex", "the codex executable")
	pkg := flag.String("pkg", "protocol", "the generated file's package")
	flag.Parse()
	if err := run(&options{out: *out, schema: *schema, codex: *codex, pkg: *pkg}); err != nil {
		fmt.Fprintln(os.Stderr, "gencodexproto:", err)
		os.Exit(1)
	}
}

type options struct {
	out, schema, codex, pkg string
	// version is codex's, when the schema directory is given.
	version string
	// roots replaces the harness's own, for tests.
	roots []string
}

func run(o *options) error {
	dir := o.schema
	version := o.version
	if dir == "" {
		tmp, err := os.MkdirTemp("", "gencodexproto-")
		if err != nil {
			return err
		}
		defer func() { _ = os.RemoveAll(tmp) }()
		if version, err = codexOutput(o.codex, "--version"); err != nil {
			return err
		}
		if _, err := codexOutput(o.codex, "app-server", "generate-json-schema", "--experimental", "--out", tmp); err != nil {
			return err
		}
		dir = tmp
	}
	defs, err := loadBundle(dir)
	if err != nil {
		return err
	}
	header := "// Code generated by slop-bot/cmd/gencodexproto from `codex app-server generate-json-schema --experimental`; DO NOT EDIT.\n"
	if version != "" {
		header += "// Schema of " + version + ".\n"
	}
	rs := roots
	if o.roots != nil {
		rs = o.roots
	}
	src, err := newGenerator(o.pkg, header, defs).generate(rs, methodGroups)
	if err != nil {
		return err
	}
	if err := os.WriteFile(o.out, src, 0o600); err != nil {
		return err
	}
	// The repo marks generated files for review tools; the generator
	// keeps that mark beside its output.
	attrs := "# " + filepath.Base(o.out) + " is written by slop-bot/cmd/gencodexproto\n" +
		"# (`go generate ./internal/harness/codex/protocol`).\n" +
		filepath.Base(o.out) + " linguist-generated=true\n"
	return os.WriteFile(filepath.Join(filepath.Dir(o.out), ".gitattributes"), []byte(attrs), 0o600)
}

func codexOutput(codex string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	out, err := exec.CommandContext(ctx, codex, args...).Output() // #nosec G204 -- the developer's own codex, run by go generate
	if err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			return "", fmt.Errorf("%s %s: %w: %s", codex, strings.Join(args, " "), err, ee.Stderr)
		}
		return "", fmt.Errorf("%s %s: %w", codex, strings.Join(args, " "), err)
	}
	return strings.TrimSpace(string(out)), nil
}
