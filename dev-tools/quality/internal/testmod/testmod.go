// Package testmod writes scratch Go modules for the tests.
package testmod

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

// Path is the scratch modules' import path.
const Path = "example.com/scratch"

// Generated is a file header that marks a file generated.
const Generated = "// Code generated by testmod. DO NOT EDIT.\n\n"

// Write makes a module at a new temporary directory, with a go.mod for
// Path and the given files (module-relative slash paths to contents).
func Write(t testing.TB, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	WriteFiles(t, dir, map[string]string{"go.mod": "module " + Path + "\n\ngo 1.24\n"})
	WriteFiles(t, dir, files)
	return dir
}

// WriteFiles writes files under dir.
func WriteFiles(t testing.TB, dir string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o750))
		require.NoError(t, os.WriteFile(p, []byte(content), 0o600))
	}
}
