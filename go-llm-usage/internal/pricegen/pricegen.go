// Package pricegen turns OpenRouter's GET /api/v1/models response into the
// pricing package's generated table. It is separate from the command so a
// test can run it against a recorded response, never the network.
package pricegen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"math/big"
	"sort"
	"strings"
	"time"
)

// Entry is one model's prices in micro-dollars per million tokens: the
// unit that keeps OpenRouter's per-token decimal prices integers.
type Entry struct {
	Model      string
	Input      int64
	Output     int64
	CacheRead  int64
	CacheWrite int64
}

type modelsResponse struct {
	Data []struct {
		ID      string `json:"id"`
		Pricing struct {
			Prompt          string `json:"prompt"`
			Completion      string `json:"completion"`
			InputCacheRead  string `json:"input_cache_read"`
			InputCacheWrite string `json:"input_cache_write"`
		} `json:"pricing"`
	} `json:"data"`
}

// Parse reads a models response into entries, sorted by model.
//
// Skipped: "~" ids, which are floating aliases ("latest") whose price
// moves with whatever they point at; and models with negative or
// unparseable prompt or completion prices (OpenRouter's dynamic routers
// say -1). A missing cache price falls back to the prompt price: a model
// without cache pricing doesn't cache, so it charges cached tokens as
// input. Tiered "overrides" (long-context prices) are ignored, since an
// aggregate record can't know each request's prompt size; estimates for
// very long prompts on such models are low.
func Parse(r io.Reader) ([]Entry, error) {
	var resp modelsResponse
	dec := json.NewDecoder(r)
	if err := dec.Decode(&resp); err != nil {
		return nil, fmt.Errorf("pricegen: decode models: %w", err)
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, fmt.Errorf("pricegen: decode models: trailing data after the response")
	}
	var entries []Entry
	seen := map[string]bool{}
	for _, m := range resp.Data {
		if m.ID == "" || strings.HasPrefix(m.ID, "~") || seen[m.ID] {
			continue
		}
		input, okIn := perMillionMicros(m.Pricing.Prompt)
		output, okOut := perMillionMicros(m.Pricing.Completion)
		if !okIn || !okOut {
			continue
		}
		e := Entry{Model: m.ID, Input: input, Output: output, CacheRead: input, CacheWrite: input}
		if v, ok := perMillionMicros(m.Pricing.InputCacheRead); ok {
			e.CacheRead = v
		}
		if v, ok := perMillionMicros(m.Pricing.InputCacheWrite); ok {
			e.CacheWrite = v
		}
		seen[m.ID] = true
		entries = append(entries, e)
	}
	if len(entries) == 0 {
		return nil, fmt.Errorf("pricegen: no priced models in the response")
	}
	SortEntries(entries)
	return entries, nil
}

// SortEntries puts entries in the order Version hashes them: by model.
func SortEntries(entries []Entry) {
	sort.Slice(entries, func(i, j int) bool { return entries[i].Model < entries[j].Model })
}

var microsPerMillionTokens = big.NewRat(1_000_000*1_000_000, 1)

// perMillionMicros converts a USD-per-token decimal string exactly,
// rounding half up only past a picodollar per token.
func perMillionMicros(usdPerToken string) (int64, bool) {
	if usdPerToken == "" {
		return 0, false
	}
	v, ok := new(big.Rat).SetString(usdPerToken)
	if !ok || v.Sign() < 0 {
		return 0, false
	}
	v.Mul(v, microsPerMillionTokens)
	num, den := v.Num(), v.Denom()
	q := new(big.Int).Mul(num, big.NewInt(2))
	q.Add(q, den)
	q.Quo(q, new(big.Int).Mul(den, big.NewInt(2)))
	if !q.IsInt64() {
		return 0, false
	}
	return q.Int64(), true
}

// Version is the table's version: the generation date plus a hash of the
// prices, so two tables with the same version have the same prices.
// entries must be sorted (SortEntries).
func Version(entries []Entry, generated time.Time) string {
	h := sha256.New()
	for _, e := range entries {
		_, _ = fmt.Fprintf(h, "%s %d %d %d %d\n", e.Model, e.Input, e.Output, e.CacheRead, e.CacheWrite)
	}
	return generated.UTC().Format("2006-01-02") + "." + hex.EncodeToString(h.Sum(nil))[:12]
}

// Render writes the generated Go source for package pricing.
func Render(entries []Entry, generated time.Time) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go-llm-usage/cmd/genprices from OpenRouter's GET /api/v1/models; DO NOT EDIT.\n\n")
	b.WriteString("package pricing\n\n")
	fmt.Fprintf(&b, "const generatedVersion = %q\n\n", Version(entries, generated))
	b.WriteString("var generatedPrices = map[string]Price{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: {Input: %d, Output: %d, CacheRead: %d, CacheWrite: %d},\n",
			e.Model, e.Input, e.Output, e.CacheRead, e.CacheWrite)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("pricegen: format: %w", err)
	}
	return out, nil
}
